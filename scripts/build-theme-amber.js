// Builds public/css/themes/<theme>-amber.css from public/css/amber.css for each festival theme that stands
// on the everyday amber look (icon tiles, KPI sparklines, rank badges, the open sidebar...) instead of the
// plain pre-amber look every other festival theme falls back to: Diwali and Chhath. Every amber rule is
// scoped :root:not([data-theme]); this copies them with that scope changed to :root[data-theme="<theme>"].
// Each theme's css @imports its copy first, so its own rules still win. (dashAmberOn() in
// public/js/dashboard.js lists the same themes, for the amber dashboard widgets.)
//
// Run after any change to amber.css:   node scripts/build-theme-amber.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'public/css/amber.css'), 'utf8');
['diwali', 'chhath'].forEach(function (theme) {
  const out = src
    .split(':root.sb-pinned:not([data-theme])').join(':root.sb-pinned[data-theme="' + theme + '"]')
    .split(':root:not([data-theme])').join(':root[data-theme="' + theme + '"]');
  const head = '/* GENERATED by scripts/build-theme-amber.js from public/css/amber.css — do not edit by hand;\n' +
               '   change amber.css and run the script again. The amber look, scoped to the ' + theme[0].toUpperCase() + theme.slice(1) + ' theme. */\n';
  fs.writeFileSync(path.join(root, 'public/css/themes/' + theme + '-amber.css'), head + out);
  console.log(theme + '-amber.css written, ' + (out.match(new RegExp('data-theme="' + theme + '"', 'g')) || []).length + ' scoped selectors');
});
